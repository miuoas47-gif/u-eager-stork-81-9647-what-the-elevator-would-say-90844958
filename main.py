#!/usr/bin/env python3
"""What the elevator would say if it could talk.

Prints exactly one line to stdout and exits 0. Fully deterministic:
no time, randomness, or network involved.
"""


def main():
    print(
        "I've carried thousands of you up and down for ten years, "
        "and not one of you has ever asked how MY day is going."
    )


if __name__ == "__main__":
    main()
